#!/usr/bin/env python3
"""Generate the Project-R theme's SVG assets from a single source of truth.

Outputs (all committed to the repo):

* ``badges/{native,emu,building,build-error}.svg`` - the four status badges
* ``badges/building/000.svg`` .. ``100.svg``      - BUILDING with progress %
* ``badges/manifest.json``                        - machine-readable pr-meta contract
* ``systems/logos/{ps3,xbox360,ps4,switch,ps5}.svg`` - original text wordmarks
* ``core/images/white.svg``                       - flat fill, tinted via ``<color>``

All lettering is converted to vector outlines from JetBrains Mono (OFL-1.1) so the
SVGs never depend on ``<text>`` support or installed fonts in ES-DE's LunaSVG renderer.

This is a dev-time tool and needs fontTools (``pip install fonttools``).
``--check`` regenerates in memory and fails if any committed file differs (used in CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_BOLD = ROOT / "core" / "fonts" / "JetBrainsMono-Bold.ttf"
FONT_REGULAR = ROOT / "core" / "fonts" / "JetBrainsMono-Regular.ttf"

THEME_VERSION = "0.1.0"

# Project-R palette. Badge colours are fixed by the design spec (section 4,
# "Sistema de Badges ES-DE"); red is reserved for real errors only.
INK = "#0d0d1a"  # text on badges (also the deep surface colour)
TEXT = "#ffffff"
TEXT_MUTED = "#888888"

BADGES = {
    # state value written by pr-meta -> (file name, fill colour, label)
    "NATIVE": ("native.svg", "#4ecdc4", "NATIVE"),
    "EMU": ("emu.svg", "#f5a623", "EMU"),
    "BUILDING": ("building.svg", "#4a9eff", "BUILDING"),
    "BUILD ERROR": ("build-error.svg", "#e94560", "BUILD ERROR"),
}

# Badge canvas: 5:1. Every badge (including progress variants) uses the same
# canvas so the theme's maxSize box renders them identically.
BADGE_W = 360
BADGE_H = 72
BADGE_RADIUS = 10
LABEL_SIZE = 34  # px; JetBrains Mono cap height 730/1000 -> ~24.8 px caps
PAD_X = 20
BAR_Y = 51
BAR_H = 8

# Original wordmarks for the standalone-emulator systems from the spec. These are
# plain monospace lettering of the platform name (nominative use), not console logos.
SYSTEM_MARKS = {
    "ps3": ("PS3", "PLAYSTATION 3"),
    "xbox360": ("X360", "XBOX 360"),
    "ps4": ("PS4", "PLAYSTATION 4"),
    "switch": ("SWITCH", "NINTENDO SWITCH"),
    "ps5": ("PS5", "PLAYSTATION 5 - EXPERIMENTAL"),
}
MARK_W = 540
MARK_H = 180
MARK_CODE_SIZE = 100
MARK_SUB_SIZE = 24

OVERRIDE_DIR = "~/ES-DE/pr-badges"


def fmt(value: float) -> str:
    """Compact, deterministic number formatting for path data."""
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


class Outliner:
    """Turns a string into SVG path data using a font's glyph outlines."""

    def __init__(self, font_path: Path) -> None:
        self.font = TTFont(font_path)
        self.glyphs = self.font.getGlyphSet()
        self.cmap = self.font.getBestCmap()
        self.hmtx = self.font["hmtx"]
        self.upm = self.font["head"].unitsPerEm
        self.cap_height = self.font["OS/2"].sCapHeight

    def _glyph(self, char: str) -> str:
        try:
            return self.cmap[ord(char)]
        except KeyError as exc:  # pragma: no cover - guards against typos in labels
            raise ValueError(f"glyph for {char!r} missing from {self.font}") from exc

    def width(self, text: str, size: float) -> float:
        return sum(self.hmtx[self._glyph(c)][0] for c in text) * size / self.upm

    def cap(self, size: float) -> float:
        return self.cap_height * size / self.upm

    def path(self, text: str, size: float, x: float, baseline: float) -> str:
        scale = size / self.upm
        pen = SVGPathPen(self.glyphs, ntos=fmt)
        cursor = 0
        for char in text:
            name = self._glyph(char)
            transform = (scale, 0, 0, -scale, x + cursor * scale, baseline)
            self.glyphs[name].draw(TransformPen(pen, transform))
            cursor += self.hmtx[name][0]
        return pen.getCommands()


def svg_document(width: int, height: int, comment: str, body: list[str]) -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f"<!-- {comment} Generated by tools/generate_assets.py - do not edit. CC0-1.0 -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">',
    ]
    lines += [f"  {item}" for item in body]
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def badge_svg(bold: Outliner, state: str, progress: int | None = None) -> str:
    _, fill, label = BADGES[state]
    body = [
        f'<rect x="0" y="0" width="{BADGE_W}" height="{BADGE_H}" '
        f'rx="{BADGE_RADIUS}" ry="{BADGE_RADIUS}" fill="{fill}"/>'
    ]
    if progress is None:
        baseline = BADGE_H / 2 + bold.cap(LABEL_SIZE) / 2
        x = (BADGE_W - bold.width(label, LABEL_SIZE)) / 2
        body.append(f'<path fill="{INK}" d="{bold.path(label, LABEL_SIZE, x, baseline)}"/>')
        comment = f"Project-R status badge {state} ({fill})."
    else:
        if not 0 <= progress <= 100:
            raise ValueError("progress must be within 0..100")
        baseline = 40
        percent = f"{progress}%"
        px = BADGE_W - PAD_X - bold.width(percent, LABEL_SIZE)
        body.append(f'<path fill="{INK}" d="{bold.path(label, LABEL_SIZE, PAD_X, baseline)}"/>')
        body.append(f'<path fill="{INK}" d="{bold.path(percent, LABEL_SIZE, px, baseline)}"/>')
        track_w = BADGE_W - 2 * PAD_X
        body.append(
            f'<rect x="{PAD_X}" y="{BAR_Y}" width="{track_w}" height="{BAR_H}" '
            f'rx="{BAR_H / 2:g}" ry="{BAR_H / 2:g}" fill="{INK}" fill-opacity="0.3"/>'
        )
        if progress > 0:
            fill_w = fmt(track_w * progress / 100)
            body.append(
                f'<rect x="{PAD_X}" y="{BAR_Y}" width="{fill_w}" height="{BAR_H}" '
                f'rx="{BAR_H / 2:g}" ry="{BAR_H / 2:g}" fill="{INK}"/>'
            )
        comment = f"Project-R status badge BUILDING {progress}% ({fill})."
    return svg_document(BADGE_W, BADGE_H, comment, body)


def mark_svg(bold: Outliner, regular: Outliner, system: str) -> str:
    code, subtitle = SYSTEM_MARKS[system]
    code_x = (MARK_W - bold.width(code, MARK_CODE_SIZE)) / 2
    sub_x = (MARK_W - regular.width(subtitle, MARK_SUB_SIZE)) / 2
    body = [
        f'<path fill="{TEXT}" d="{bold.path(code, MARK_CODE_SIZE, code_x, 108)}"/>',
        f'<path fill="{TEXT_MUTED}" d="{regular.path(subtitle, MARK_SUB_SIZE, sub_x, 152)}"/>',
    ]
    comment = f"Project-R system wordmark for '{system}' (original lettering, not a logo)."
    return svg_document(MARK_W, MARK_H, comment, body)


def white_svg() -> str:
    body = ['<rect x="0" y="0" width="8" height="8" fill="#ffffff"/>']
    return svg_document(8, 8, "Flat white fill, tinted by the theme's color property.", body)


def manifest() -> str:
    data = {
        "theme": "project-r",
        "version": THEME_VERSION,
        "esde": "3.5.0",
        "mechanism": "image element gameOverridePath (ES-DE THEMES.md, image element)",
        "overrideDir": OVERRIDE_DIR,
        "overrideFile": "{overrideDir}/{system}/{stem}.svg",
        "states": {
            state: {"file": f"badges/{name}", "color": color}
            for state, (name, color, _) in BADGES.items()
        },
        "buildingProgressFile": "badges/building/{progress:03d}.svg",
        "buildingProgressRange": [0, 100],
    }
    return json.dumps(data, indent=2) + "\n"


def build() -> dict[Path, str]:
    bold = Outliner(FONT_BOLD)
    regular = Outliner(FONT_REGULAR)
    files: dict[Path, str] = {}
    for state, (name, _, _) in BADGES.items():
        files[ROOT / "badges" / name] = badge_svg(bold, state)
    for progress in range(0, 101):
        files[ROOT / "badges" / "building" / f"{progress:03d}.svg"] = badge_svg(
            bold, "BUILDING", progress
        )
    files[ROOT / "badges" / "manifest.json"] = manifest()
    for system in SYSTEM_MARKS:
        files[ROOT / "systems" / "logos" / f"{system}.svg"] = mark_svg(bold, regular, system)
    files[ROOT / "core" / "images" / "white.svg"] = white_svg()
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if committed assets differ")
    args = parser.parse_args(argv)

    stale = []
    for path, content in build().items():
        rel = path.relative_to(ROOT).as_posix()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {rel}")

    if stale:
        print("Generated assets are out of date (run tools/generate_assets.py):", file=sys.stderr)
        for rel in stale:
            print(f"  {rel}", file=sys.stderr)
        return 1
    if args.check:
        print("generated assets are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
